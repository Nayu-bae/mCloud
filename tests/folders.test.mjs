import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { Users } from '../dist/users.js';
import { Files } from '../dist/files.js';
import { openDatabase } from '../dist/database.js';
import { createApp } from '../dist/app.js';

test('private nested folders, moves, destination uploads and empty-only deletion', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'mcloud-folders-test-'));
  const database = join(dir, 'test.sqlite');
  const users = new Users(database);
  const files = new Files(database);
  await users.bootstrap('owner','owner-test-password');
  const member = await users.add('member','member-test-password');
  const server = createApp(users,false,{files,directory:join(dir,'uploads')}).listen(0,'127.0.0.1');
  await once(server,'listening');
  const base=`http://127.0.0.1:${server.address().port}`;
  const json=(path,method,body,cookie='')=>fetch(base+path,{method,headers:{'Content-Type':'application/json',cookie},body:JSON.stringify(body)});
  const login=async(username,password)=>(await json('/api/login','POST',{username,password})).headers.get('set-cookie').split(';')[0];
  try {
    const owner=await login('owner','owner-test-password');
    const cookie=await login('member','member-test-password');
    assert.equal((await json('/api/files/folders','POST',{name:'Denied'})).status,401);
    const create=await json('/api/files/folders','POST',{name:'Documents'},cookie);
    assert.equal(create.status,201);
    const folder=(await create.json()).folder;
    const child=(await (await json('/api/files/folders','POST',{name:'Notes',parentId:folder.id},cookie)).json()).folder;
    assert.equal(child.parent_id,folder.id);
    assert.equal((await json('/api/files/folders','POST',{name:'documents'},cookie)).status,409);
    assert.equal((await json('/api/files/folders','POST',{name:'../unsafe'},cookie)).status,400);
    assert.equal((await json('/api/files/folders','POST',{name:'Private',parentId:folder.id},owner)).status,404);
    assert.equal((await json(`/api/files/folders/${folder.id}`,'PATCH',{name:'Stolen'},owner)).status,404);
    assert.equal((await json(`/api/files/folders/${folder.id}`,'DELETE',{},owner)).status,404);
    const upload = (auth, destination) => fetch(base+'/api/files',{method:'POST',headers:{cookie:auth,'Content-Type':'application/octet-stream','X-File-Name':'notes.txt','X-Folder-Id':String(destination)},body:'private notes'});
    assert.equal((await upload(owner,child.id)).status,404);
    const result=await upload(cookie,child.id);assert.equal(result.status,201);
    const file=(await result.json()).file;assert.equal(file.folderId,child.id);
    assert.equal((await json(`/api/files/folders/${child.id}`,'DELETE',{},cookie)).status,409);
    assert.equal((await json(`/api/files/folders/${folder.id}`,'DELETE',{},cookie)).status,409);
    const other=(await (await json('/api/files/folders','POST',{name:'Other'},owner)).json()).folder;
    assert.equal((await json(`/api/files/${file.id}`,'PATCH',{folderId:other.id},cookie)).status,404);
    assert.equal((await json(`/api/files/${file.id}`,'PATCH',{folderId:null},owner)).status,404);
    const db=openDatabase(database);
    assert.throws(()=>db.prepare('UPDATE user_files SET folder_id = ? WHERE file_id = ?').run(other.id,file.id));
    assert.throws(()=>db.prepare('INSERT INTO folders(user_id,parent_id,name) VALUES(?,?,?)').run(member.id,other.id,'Forbidden'));
    db.close();
    assert.equal((await json(`/api/files/${file.id}`,'PATCH',{folderId:null},cookie)).status,200);
    assert.equal(files.getForUser(member.id,file.id).folder_id,null);
    assert.equal((await json(`/api/files/${file.id}`,'PATCH',{folderId:folder.id},cookie)).status,200);
    assert.equal((await json(`/api/files/folders/${folder.id}`,'PATCH',{name:'My documents'},cookie)).status,200);
    assert.equal((await json(`/api/files/folders/${child.id}`,'DELETE',{},cookie)).status,204);
    const listing=await (await fetch(base+'/api/files',{headers:{cookie}})).json();
    assert.equal(listing.folders.length,1);assert.equal(listing.folders[0].name,'My documents');
    assert.equal(listing.files[0].folderId,folder.id);
    assert.equal((await fetch(base+`/api/files/${file.id}/download`,{headers:{cookie}})).status,200);
    assert.equal((await json(`/api/files/${file.id}`,'PATCH',{folderId:null},cookie)).status,200);
    assert.equal((await json(`/api/files/folders/${folder.id}`,'DELETE',{},cookie)).status,204);
    assert.equal(files.listForUser(member.id).length,1);
  } finally { await new Promise(resolve=>server.close(resolve)); users.close();files.close();rmSync(dir,{recursive:true,force:true}); }
});
