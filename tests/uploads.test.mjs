import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { Users } from '../dist/users.js';
import { Files } from '../dist/files.js';
import { createApp } from '../dist/app.js';

test('private uploads, download, rename, delete, limits and restart recovery', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'mcloud-upload-test-'));
  const database = join(dir, 'test.sqlite');
  const directory = join(dir, 'uploads');
  const users = new Users(database);
  const files = new Files(database);
  await users.bootstrap('owner', 'owner-test-password');
  const member = await users.add('member', 'member-test-password');
  let server = createApp(users, false, { files, directory, maxUpload: 32 }).listen(0, '127.0.0.1');
  await once(server, 'listening');
  let base = `http://127.0.0.1:${server.address().port}`;
  const login = async (username, password) => (await fetch(base+'/api/login', { method:'POST', headers:{'Content-Type':'application/json'},body:JSON.stringify({username,password}) })).headers.get('set-cookie').split(';')[0];
  const upload = (cookie, body, name='notes.txt', extra={}) => fetch(base+'/api/files', {method:'POST',headers:{cookie,'Content-Type':'application/octet-stream','X-File-Name':encodeURIComponent(name),...extra},body});
  const change = (cookie, id, method, body={}) => fetch(base+`/api/files/${id}`,{method,headers:{cookie,'Content-Type':'application/json'},body:JSON.stringify(body)});
  try {
    const owner = await login('owner','owner-test-password');
    const cookie = await login('member','member-test-password');
    assert.equal((await upload('', 'secret')).status,401);
    assert.equal((await upload(cookie, 'secret', 'notes.txt', {Origin:'https://other.example'})).status,403);
    const uploaded = await upload(cookie,'private content','私の notes.txt');
    assert.equal(uploaded.status,201);
    const file=(await uploaded.json()).file;
    assert.equal(file.size,15);
    assert.equal('storage_key' in file,false);
    const list = await fetch(base+'/api/files',{headers:{cookie}});
    assert.equal((await list.json()).files.length,1);
    assert.equal((await (await fetch(base+'/api/files',{headers:{cookie:owner}})).json()).files.length,0);
    const download = await fetch(base+`/api/files/${file.id}/download`,{headers:{cookie}});
    assert.equal(await download.text(),'private content');
    assert.match(download.headers.get('content-disposition'),/^attachment/);
    assert.equal(download.headers.get('content-type'),'application/octet-stream');
    assert.equal((await fetch(base+`/api/files/${file.id}/download`)).status,401);
    assert.equal((await fetch(base+`/api/files/${file.id}/download`,{headers:{cookie:owner}})).status,404);
    assert.equal((await change(owner,file.id,'PATCH',{name:'stolen'})).status,404);
    assert.equal((await change(owner,file.id,'DELETE')).status,404);
    assert.equal((await change(cookie,file.id,'PATCH',{name:'../../escape'})).status,400);
    assert.equal((await change(cookie,file.id,'PATCH',{name:'renamed.txt'})).status,200);
    assert.equal((await upload(cookie,'a'.repeat(33))).status,413);
    assert.equal((await upload(cookie,'test','../bad')).status,400);
    const zero = await upload(cookie,'','empty.txt');
    assert.equal(zero.status,201);
    assert.equal((await zero.json()).file.size,0);
    assert.equal((await upload(cookie,'second','renamed.txt')).status,201);
    assert.equal(readdirSync(directory).length,3);
    const injected = files.recordUpload;
    files.recordUpload = () => { throw new Error('Injected database failure'); };
    assert.equal((await upload(cookie,'fail','failure.txt')).status,500);
    files.recordUpload = injected;
    // Cleanup may finish just after the HTTP response.
    await new Promise(resolve=>setTimeout(resolve,50));
    assert.equal(readdirSync(directory).length,3);
    const stream = new ReadableStream({start(controller){controller.enqueue(new Uint8Array(33));controller.close();}});
    const oversized=await fetch(base+'/api/files',{method:'POST',headers:{cookie,'Content-Type':'application/octet-stream','X-File-Name':'too-big'},body:stream,duplex:'half'});
    assert.equal(oversized.status,413);
    await new Promise(resolve=>setTimeout(resolve,50));
    assert.equal(readdirSync(directory).length,3);
    assert.equal((await change(cookie,file.id,'DELETE')).status,204);
    assert.equal((await fetch(base+`/api/files/${file.id}/download`,{headers:{cookie}})).status,404);
    assert.equal(readdirSync(directory).length,2);
    assert.equal(files.listForUser(member.id).length,2);
    await new Promise(resolve=>server.close(resolve));
    writeFileSync(join(directory,'00000000-0000-0000-0000-000000000000'),'orphan');
    writeFileSync(join(directory,'.upload-00000000-0000-0000-0000-000000000001'),'partial');
    server=createApp(users,false,{files,directory,maxUpload:32}).listen(0,'127.0.0.1');
    await once(server,'listening');
    base=`http://127.0.0.1:${server.address().port}`;
    assert.equal(readdirSync(directory).length,2);
    const renewed=await login('member','member-test-password');
    assert.equal((await (await fetch(base+'/api/files',{headers:{cookie:renewed}})).json()).files.length,2);
  } finally {
    await new Promise(resolve=>server.close(resolve));
    users.close(); files.close(); rmSync(dir,{recursive:true,force:true});
  }
});
